PROMOS = [
    ("ZERNO10", "percent", 10, None),
    ("WELCOME", "fixed", 100, 1000),
    ("COMEBACK15", "percent", 15, None),
]


async def seed(session: AsyncSession) -> bool:
    if await session.scalar(select(func.count(Category.id))):
        return False

    cats: dict[str, Category] = {}
    for i, (name, icon) in enumerate(CATEGORIES):
        cats[name] = Category(name=name, icon=icon, sort=i)
        session.add(cats[name])

    for i, (cat, name, desc, art, price, badges, groups, sizes, tags) in enumerate(PRODUCTS):
        product = Product(
            category=cats[cat],
            name=name,
            description=desc,
            photo_url=f"art:{art}",
            base_price=price,
            badges=badges,
            modifier_groups=groups,
            tags=tags,
            sort=i,
        )
        product.sizes = [ProductSize(size=s, volume_ml=v, price=price + d) for s, v, d in sizes]
        session.add(product)

    for group, name, price in MODIFIERS:
        session.add(Modifier(group=group, name=name, price=price))

    for code, type_, value, limit in PROMOS:
        session.add(Promocode(code=code, type=type_, value=value, usage_limit=limit))

    await session.commit()
    return True
